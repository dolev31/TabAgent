"""Stateless feature primitives: pure functions of a row's own columns.

A stateless feature never looks at labels or at other rows, so it can be computed on any table, training
or held-out, without leakage. Every primitive has the signature ``fn(df, **args) -> pd.Series``.
Code generated by TabSchema's CodeExtractor may only produce stateless features (see ``card.py``).

``python:<module>:<function>`` names a primitive defined elsewhere. Modules under ``tabagent`` are always
allowed; any other module is imported only when the card is loaded with ``trust_code=True``, because loading
a card from someone else must not run their code by default.
"""

from __future__ import annotations

import importlib
import re
from collections.abc import Callable

import pandas as pd

_TOKENS = re.compile(r"[a-z0-9]+")
PYTHON_SOURCE = "python:"


def join_text(df: pd.DataFrame, cols) -> pd.Series:
    """The text of one column, or of several joined by a space; missing values count as empty text."""
    cols = [cols] if isinstance(cols, str) else list(cols)
    out = df[cols[0]].fillna("").astype(str)
    for c in cols[1:]:
        out = out + " " + df[c].fillna("").astype(str)
    return out


def column(df: pd.DataFrame, col: str) -> pd.Series:
    """The column itself."""
    return df[col]


def concat(df: pd.DataFrame, cols: list[str]) -> pd.Series:
    """Several text columns joined by a space."""
    return join_text(df, cols)


def word_count(df: pd.DataFrame, col: str) -> pd.Series:
    """Number of whitespace-separated words."""
    return join_text(df, col).map(lambda s: len(s.split())).astype(float)


def char_len(df: pd.DataFrame, col: str) -> pd.Series:
    """Number of characters."""
    return join_text(df, col).str.len().astype(float)


def jaccard(df: pd.DataFrame, a, b) -> pd.Series:
    """Token Jaccard overlap |A ∩ B| / (|A ∪ B| + 1e-9) over lowercase alphanumeric tokens."""

    def lex(x: str, y: str) -> float:
        ta, tb = set(_TOKENS.findall(x.lower())), set(_TOKENS.findall(y.lower()))
        return len(ta & tb) / (len(ta | tb) + 1e-9)

    pairs = zip(join_text(df, a), join_text(df, b), strict=True)
    return pd.Series([lex(x, y) for x, y in pairs], index=df.index)


def regex_flag(df: pd.DataFrame, col: str, pattern: str, ignore_case: bool = True) -> pd.Series:
    """1.0 where the regular expression matches, else 0.0."""
    rx = re.compile(pattern, re.I if ignore_case else 0)
    return join_text(df, col).map(lambda s: float(bool(rx.search(s))))


def digit_ratio(df: pd.DataFrame, col: str) -> pd.Series:
    """Share of characters that are digits."""
    return join_text(df, col).map(lambda s: sum(ch.isdigit() for ch in s) / len(s) if s else 0.0)


def is_question(df: pd.DataFrame, col: str) -> pd.Series:
    """1.0 where the text contains a question mark."""
    return join_text(df, col).map(lambda s: float("?" in s))


STATELESS: dict[str, Callable[..., pd.Series]] = {
    "column": column,
    "concat": concat,
    "word_count": word_count,
    "char_len": char_len,
    "jaccard": jaccard,
    "regex_flag": regex_flag,
    "digit_ratio": digit_ratio,
    "is_question": is_question,
}


def python_module(source: str) -> str | None:
    """The module a ``python:<module>:<function>`` source imports, or None for other sources."""
    if not source.startswith(PYTHON_SOURCE):
        return None
    parts = source.split(":", 2)
    if len(parts) != 3 or not parts[1] or not parts[2]:
        raise ValueError(f"a python source is 'python:<module>:<function>', got {source!r}")
    return parts[1]


def is_trusted_module(module: str) -> bool:
    """True for ``tabagent`` and its submodules, which a card may always use."""
    return module == "tabagent" or module.startswith("tabagent.")


def resolve(source: str) -> Callable[..., pd.Series]:
    """A registered primitive by name, or ``python:<module>:<function>`` for code in another module."""
    if source in STATELESS:
        return STATELESS[source]
    module = python_module(source)
    if module is not None:
        return getattr(importlib.import_module(module), source.split(":", 2)[2])
    raise KeyError(f"unknown stateless feature source {source!r}")
